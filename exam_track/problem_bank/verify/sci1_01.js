/* sci1_01 검산 — 통합과학1 Ⅰ. 과학의 기초 (측정과 정보)
 *
 * 과학은 계산 문항이 있으므로 두 가지를 함께 한다.
 *   ① 계산 문항(001·004)은 **문항의 풀이와 다른 경로로** 다시 구한다.
 *   ② 나머지는 정답 근거가 앱 본문에 실제로 있는지 확인한다(_lib_concept 의 appSource).
 * 계산이 있으므로 structCheck 에 allowC5: true 를 준다.
 */
const { appSource, structCheck } = require('./_lib_concept');
const src = appSource('통합과학1', 'sci1_basics.html');

module.exports = function ({ S, chk }) {

  // ── 001 밀도 — 문항은 "질량 ÷ 부피"로 푼다. 여기서는 거꾸로 곱해 되던진다 ──
  const m = 54.0, vAfter = 40.0, vBefore = 20.0;
  const v = vAfter - vBefore;                 // 20.0
  const d = m / v;                            // 2.70
  const back = d * v;                         // 54.0 이어야 한다
  chk(1, d.toFixed(2) + ' g/cm³',
    '밀도 ' + d.toFixed(2) + ' · 되던지기 ' + d.toFixed(2) + '×' + v.toFixed(1) + '=' + back.toFixed(1) + ' g(처음 질량과 같다)' +
    ' · 오답 경로 확인: 54.0/40.0=' + (m / vAfter).toFixed(2) + ' · 54.0/2.00=' + (m / 2).toFixed(1) + '(눈금 20.0 을 2.0 으로 읽음)');

  // ── 004 단위 환산 — 문항은 "1000 곱하고 3600 나눈다". 여기서는 초당 거리를 직접 세어 본다 ──
  const kmh = 72;
  const mPerSec = kmh * 1000 / 3600;          // 20
  const perHour = mPerSec * 3600 / 1000;      // 72 km 로 돌아와야 한다
  chk(4, mPerSec + ' m/s',
    '초당 ' + mPerSec + ' m · 되던지기 ' + mPerSec + '×3600÷1000=' + perHour + ' km/h' +
    ' · 오답 경로 확인: 72/60=' + (kmh / 60).toFixed(1) + ' · 72×1000=' + (kmh * 1000));

  // ── 002 측정값 표 — 폭과 평균을 실제로 계산해 판정을 검산한다 ──
  const gap = [27.1, 27.0, 27.2, 27.1, 27.0], eul = [25.4, 24.6, 25.3, 24.7, 25.0], byeong = [22.8, 26.9, 24.1, 27.3, 23.9];
  const avg = a => a.reduce((x, y) => x + y, 0) / a.length;
  const span = a => Math.max.apply(null, a) - Math.min.apply(null, a);
  chk(2, '갑은 정밀하지만 정확하지 않다.',
    '갑 폭 ' + span(gap).toFixed(1) + ' 평균 ' + avg(gap).toFixed(2) + '(참값 25.0 과 ' + (avg(gap) - 25).toFixed(2) + ' 차이) → 정밀·부정확' +
    ' / 을 폭 ' + span(eul).toFixed(1) + ' 평균 ' + avg(eul).toFixed(2) + ' → 정확' +
    ' / 병 폭 ' + span(byeong).toFixed(1) + ' → 부정밀');

  // ── 007 여러 번 왕복을 한꺼번에 재면 한 번당 오차가 몇 분의 일이 되는가 ──
  const err = 0.2, n = 10;
  chk(7, '여러 번 왕복하는 시간을 한꺼번에 재고 그 횟수로 나눈다.',
    '누름 오차 ' + err + '초를 ' + n + '회로 나누면 한 번당 ' + (err / n).toFixed(2) + '초 · meas 탭 새 박스 · ' + src('여러 번을 한꺼번에 재어 횟수로 나눈다'));

  // ── 011 어림 — 어느 값으로 잡아도 자릿수가 흔들리지 않는지 확인한다 ──
  const area = 9 * 7;
  chk(11, '한 사람이 서는 데 필요한 넓이를 정하고 교실 넓이를 그 값으로 나눈다.',
    '넓이 ' + area + ' m² · 0.5 m²/인 → ' + (area / 0.5) + '명 · 1.0 m²/인 → ' + area + '명 (둘 다 백 명 안팎) · ' + src('자릿수만이라도 먼저 가늠하면'));

  // ── 나머지는 앱 근거 대조 ──
  chk(3, '참값을 모르면 정확도를 따질 수 없지만, 정밀도는 반복해 잰 값들만으로 알 수 있다.',
    'meas 탭 표 · ' + src('참값에 얼마나 가까운가') + ' / ' + src('여러 번 쟀을 때 얼마나 모여 있는가'));

  chk(5, '다섯 값에서 각각 3.0 g 을 빼면 된다.',
    'meas 탭 새 박스 · ' + src('어긋난 양만큼 빼야') + ' / ' + src('매번 같은 방향으로'));

  chk(6, '유도량은 기본량의 곱과 나눗셈으로 정해지고 단위도 그 조합이 된다.',
    'unit 탭 · ' + src('유도량 = 기본량의 조합') + ' / ' + src('속력 = 길이 ÷ 시간'));

  chk(8, '연속인 소리를 숫자로 바꿀 때 자주 잴수록 원래 신호에 가까워진다.',
    '자료 수치 = 전화 음질 8,000 Hz · CD 음질 44,100 Hz(실제 값) · digital 탭 새 박스 · ' + src('1초에 44,100번'));

  chk(9, '널리 쓰이지만, 연속인 값을 띄엄띄엄하게 바꾸며 원래의 일부를 잃는다.',
    'digital 탭 🔑박스 · ' + src('잡음에 강하고, 복제·전송·저장·계산이 쉽다') + ' / 새 박스 · ' + src('가까워질 뿐'));

  chk(10, '방향이 그때그때 다른 흩어짐은 줄지만, 늘 같은 방향의 치우침은 남는다.',
    'meas 탭 새 박스 · ' + src('우연 오차') + ' / ' + src('계통 오차') + ' / ' + src('백 번을 재도 평균이 그만큼 치우친 채로 남는다'));

  chk(12, '1초 사이의 변화와 소수 둘째 자리 아래의 변화는 남지 않는다.',
    'digital 탭 새 박스 · ' + src('얼마나 자주 재는가') + ' / ' + src('얼마나 잘게 적는가') + ' / ' + src('따로 정해지는 설정'));

  structCheck(S, { set: 'sci1_01', allowC5: true });
};
