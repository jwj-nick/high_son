/* sci1_02 검산 — 통합과학1 Ⅱ. 빅뱅과 원소의 생성
 * 계획서 §3-2 대로 이 단원에는 계산 문항을 두지 않았다(계산이 자연스럽지 않은 단원).
 * 그래서 검산은 ① 자료 문항의 수치 정합 ② 정답 근거의 앱 존재 ③ 구조 자기검사 셋이다.
 */
const { appSource, structCheck } = require('./_lib_concept');
const src = appSource('통합과학1', 'sci1_bigbang.html');

module.exports = function ({ S, chk }) {

  // ── 001·008 자료의 비율이 실제로 앱 값과 같은지, 그리고 합이 말이 되는지 ──
  const univ = { H: 74, He: 24, rest: 2 };
  const earth = { Fe: 32, O: 30, Si: 15, Mg: 14 };
  const body = { O: 65, C: 18, H: 10, N: 3 };
  const sum = o => Object.keys(o).reduce((s, k) => s + o[k], 0);
  chk(1, '우주에서 2 % 뿐인 무거운 원소들이 지구에서는 대부분을 차지한다.',
    '우주 합 ' + sum(univ) + ' % · 지구 상위 4 합 ' + sum(earth) + ' % · 지구의 네 원소는 모두 우주의 "그 밖 2 %" 쪽이다 · ' +
    src('수소 (H) 74%') + ' / ' + src('철 (Fe) 32%'));

  const overlap = Object.keys(earth).filter(k => k in body);
  chk(8, '두 목록에 함께 오르는 것은 산소뿐이고, 사람 몸 쪽은 모두 가벼운 원소다.',
    '겹치는 원소 ' + overlap.join(',') + ' (' + overlap.length + '개) · 사람 몸 합 ' + sum(body) + ' % · ' +
    src('산소 (O) 65%') + ' / ' + src('탄소 (C) 18%'));

  // ── 나머지는 앱 근거 대조 ──
  chk(2, '빅뱅 직후에 대부분 만들어졌고, 별 안에서도 수소가 바뀌며 계속 만들어진다.',
    'bang 탭 · ' + src('수소·헬륨이 먼저 생겼다') + ' / star 탭 · ' + src('가벼운 원소가 무거운 원소로 바뀐다') + ' (양쪽 모두에 해당하는 드문 원소)');

  chk(3, '탄소·산소·철은 별에서, 금·우라늄은 초신성에서',
    'star 탭 🛑박스 · ' + src('핵융합은 철(Fe) 까지만') + ' / 💫박스 · ' + src('철보다 무거운 원소(금·은·우라늄 등)'));

  chk(4, '그 별에 수소와 헬륨이 있다.',
    'earth 탭 🔭박스 · ' + src('원소마다 흡수하는 빛의 색') + ' ' + src('별빛을 분석하면 어떤 원소가 있는지 읽어낼 수 있다'));

  chk(5, '빅뱅이 만든 것은 수소와 헬륨뿐이라 땅과 몸을 이룰 무거운 원소가 없었다.',
    'bang 탭 🔑박스 · ' + src('더 무거운 원소는 이때 거의 못 만들어졌다') + ' · 시간 검산 138 − 46 = ' + (138-46) + '억 년');

  chk(6, '어느 은하에서 보아도 다른 은하들이 멀어져 보이기 때문이다.',
    'bang 탭 ⚠박스 · 39차에 보강한 줄 · ' + src('어느 은하에서 보아도 다른 은하가 멀어져 보인다') + ' ' + src('중심도 바깥도 없다'));

  chk(7, '별이 만든 무거운 원소의 양이 처음의 수소·헬륨보다 아주 적기 때문이다.',
    'bang 탭 · ' + src('나머지 모든 원소를 합쳐도 약 2%'));

  chk(9, '바르게 짚었고 머리글자를 따 CHON 이라 부른다.',
    'earth 탭 🔑박스 · ' + src('탄소(C)·수소(H)·산소(O)·질소(N)') + ' ' + src('CHON'));

  chk(10, '우리 몸의 탄소·산소 같은 원자가 별의 내부와 죽음에서 만들어졌다는 뜻이다.',
    'intro · ' + src('별이 죽으며 만든 것이다') + ' / world · ' + src('우리 몸을 이루는 원자는 별에서 왔다'));

  chk(11, '앞은 가벼운 핵을 합치고, 뒤는 무거운 핵을 쪼갠다.',
    'star 탭 · ' + src('핵융합') + ' ' + src('가벼운 원소가 무거운 원소로 바뀐다') + ' / world · ' + src('수소 핵융합') + ' (핵분열과의 대비는 앱에 없어 이 문항이 새로 요구하는 판단이다)');

  chk(12, '어떤 원소가 있는지는 알지만, 생명이 있는지는 알 수 없다.',
    'earth 탭 🔭박스 · ' + src('직접 가보지 않고도 별·태양의 원소를 안다'));

  structCheck(S, { set: 'sci1_02', allowC8: true });
};
