// prob_06 정답키 재검산 — 표에서 값을 옮겨 적는 대신, 표준정규분포의 넓이를 **직접 수치적분**해 확인한다.
// 표가 주는 0.3413·0.4332·0.4772·0.4938 자체가 맞는지도 같이 검산되고, 문항의 표준화 계산과 완전히 다른 경로가 된다.
module.exports = function ({ chk, near }) {
  const R4 = (v) => Math.round(v * 1e4) / 1e4;
  // 표준정규분포의 밀도함수를 심프슨 적분으로 — 문항이 쓰는 표를 쓰지 않는다
  const phi = (z) => Math.exp(-z * z / 2) / Math.sqrt(2 * Math.PI);
  const I = (a, b, N) => { N = N || 2000; const h = (b - a) / N; let s = phi(a) + phi(b); for (let i = 1; i < N; i++) s += phi(a + i * h) * (i % 2 ? 4 : 2); return s * h / 3; };
  const P = (a, b) => R4(I(a, b));                 // P(a ≤ Z ≤ b)
  const tail = (z) => R4(0.5 - I(0, z));           // P(Z ≥ z)
  const zOf = (x, m, s) => (x - m) / s;
  // 꼬리 확률로부터 z 를 되찾는다(이분법)
  const zFromTail = (p) => { let lo = 0, hi = 6; for (let i = 0; i < 80; i++) { const md = (lo + hi) / 2; if (0.5 - I(0, md) > p) lo = md; else hi = md; } return Math.round((lo + hi) / 2 * 1e4) / 1e4; };

  // 표 자체를 먼저 검산해 둔다
  const T = { 1: R4(I(0, 1)), 1.5: R4(I(0, 1.5)), 2: R4(I(0, 2)), 2.5: R4(I(0, 2.5)) };

  // 1 — 확률밀도함수의 전체 넓이가 1 이 되는 k 를 훑어 찾는다
  // 넓이를 사다리꼴 공식이 아니라 잘게 쪼개 더해 구한다
  const area1 = (k) => { let a = 0; const N = 20000, h = 6 / N; for (let i = 0; i < N; i++) a += k * (i + 0.5) * h * h; return a; };
  let k1 = null;
  for (let k = 0.0001; k <= 1; k += 0.0000005) { if (Math.abs(area1(k) - 1) < 5e-6) { k1 = Math.round(k * 1e7) / 1e7; break; } }
  chk(1, '1/18', '0~6 을 2 만 조각으로 쪼개 넓이를 더했을 때 1 이 되는 k = ' + k1 + ' (1/18 = ' + Math.round(1 / 18 * 1e7) / 1e7 + ') · 그때 넓이 ' + Math.round(area1(k1) * 1e6) / 1e6 + ' · 밑변×높이로 보면 k = ' + Math.round(1 / 36 * 1e7) / 1e7 + ' 인데 삼각형이라 그 두 배인 1/18 이 맞다(보기 1/6 은 6k=1 로 본 것, 보기 1/36 은 36k=1 로 본 것)');

  // 2 — 연속확률변수를 실제로 하나 만들어(0~0.5 균등, f=2) 각 보기를 판정한다
  const f2 = 2, span = 0.5;
  chk(2, 'P(X = 2) = 0 이다', '0~0.5 에서 f(x)=2 인 분포를 지으면 전체 넓이 ' + (span * f2) + ' = 1 인데 f 의 값은 ' + f2 + ' 로 1 을 넘는다(보기 "f 는 1 을 넘을 수 없다"는 틀림) · 한 점의 넓이는 폭이 0 이라 ' + 0 + ' · 등호를 넣은 구간과 뺀 구간의 넓이 차 = ' + 0 + ' (보기 "다르다"는 틀림)');

  // 3 — 수치적분으로 오른쪽 꼬리를 직접 잰다
  const a3 = zOf(76, 82, 3), b3 = zOf(88, 82, 3);
  chk(3, '0.9544', '표준화 ' + a3 + ' ~ ' + b3 + ' · 수치적분 P = ' + P(a3, b3) + ' · 한쪽만 읽으면 ' + T[2] + ' (보기 0.4772) · 바깥쪽 두 꼬리 ' + R4(1 - P(a3, b3)) + ' (보기 0.0456) · z 를 1 로 보면 ' + P(-1, 1) + ' (보기 0.6826)');

  // 4 — 평균이 구간 안에 있는 경우
  const a4 = zOf(55, 64, 9), b4 = zOf(82, 64, 9);
  chk(4, '0.8185', '표준화 ' + a4 + ' ~ ' + b4 + ' · 수치적분 P = ' + P(a4, b4) + ' · 두 넓이를 빼면 ' + R4(T[2] - T[1]) + ' (보기 0.1359) · 오른쪽을 z=1 로 보면 ' + P(-1, 1) + ' (보기 0.6826) · 바깥쪽 ' + R4(1 - P(a4, b4)) + ' (보기 0.1815)');

  // 5 — 두 조건을 만족하는 (m, σ) 를 훑어 찾는다
  // 왼쪽 조건이 z = −1 을 뜻하므로 m = 46 + σ 로 두고, σ 만 훑어 오른쪽 조건까지 맞는 값을 찾는다
  let m5 = null, s5 = null;
  for (let s = 1; s <= 30; s += 0.01) {
    const m = 46 + s;
    if (Math.abs(tail((70 - m) / s) - 0.0228) < 0.0003) { m5 = Math.round(m * 100) / 100; s5 = Math.round(s * 100) / 100; break; }
  }
  chk(5, '8', '조건을 만족하는 (m, σ) 를 훑어 찾으면 m = ' + m5 + ', σ = ' + s5 + ' · 그때 P(X≤46) = ' + R4(0.5 - I(0, (m5 - 46) / s5)) + ' P(X≥70) = ' + tail((70 - m5) / s5) + ' · 두 값의 차 24 는 3σ 라 σ 로 보면 24 (보기 24), 2 로 나누면 12 (보기 12)');

  // 6 — 0 을 사이에 둔 구간
  chk(6, '0.2255', '왼쪽 꼬리 P(Z ≤ −1.5) = ' + tail(1.5) + ' 오른쪽 꼬리 P(Z ≥ 1) = ' + tail(1) + ' → 합 ' + R4(tail(1.5) + tail(1)) + ' · 그 사이 구간은 ' + P(-1.5, 1) + ' 이라 더하면 1 이 된다 (보기 0.7745) · 표의 두 값을 빼면 ' + R4(T[1.5] - T[1]) + ' (보기 0.0919) · 왼쪽 꼬리를 두 배 하면 ' + R4(2 * tail(1.5)) + ' (보기 0.1336)');

  // 7 — 평균의 같은 쪽에 있는 두 값
  const a7 = zOf(53, 47, 6), b7 = zOf(62, 47, 6);
  chk(7, '0.1525', '표준화 ' + a7 + ' ~ ' + b7 + ' (둘 다 양수) · 수치적분 P = ' + P(a7, b7) + ' · 더하면 ' + R4(T[1] + T[2.5]) + ' (보기 0.8351) · 2.5 를 2 로 반올림하면 ' + R4(T[2] - T[1]) + ' (보기 0.1359) · 오른쪽만 읽으면 ' + T[2.5] + ' (보기 0.4938)');

  // 8 — 이항분포를 실제로 쌓아 만든 뒤 정규근사와 맞춰 본다
  const n8 = 400, p8 = 0.5;
  const mu8 = n8 * p8, sg8 = Math.sqrt(n8 * p8 * (1 - p8));
  // 이항분포의 실제 꼬리 확률(정규근사 없이 로그 계산으로 누적)
  let lg = new Array(n8 + 1).fill(0); for (let i = 1; i <= n8; i++) lg[i] = lg[i - 1] + Math.log(i);
  let exact = 0; for (let k = 220; k <= n8; k++) exact += Math.exp(lg[n8] - lg[k] - lg[n8 - k] + k * Math.log(p8) + (n8 - k) * Math.log(1 - p8));
  chk(8, '0.0228', 'np = ' + mu8 + ' σ = √(npq) = ' + sg8 + ' → z = ' + zOf(220, mu8, sg8) + ' · 근사값 ' + tail(zOf(220, mu8, sg8)) + ' · 이항분포로 직접 누적한 실제 값 ' + R4(exact) + ' (근사가 잘 맞는다) · σ 를 √n = ' + Math.sqrt(n8) + ' 으로 잘못 보면 z = ' + zOf(220, mu8, Math.sqrt(n8)) + ' 이라 ' + tail(zOf(220, mu8, Math.sqrt(n8))) + ' (보기 0.1587) · 표 값 그대로면 ' + T[2] + ' (보기 0.4772) · 왼쪽 전부 ' + R4(1 - tail(2)) + ' (보기 0.9772)');

  // 9 — np = 75 가 되는 n 을 훑어 찾은 뒤 σ 를 잰다
  let n9 = null;
  for (let n = 1; n <= 2000; n++) if (Math.abs(n * 0.25 - 75) < 1e-9) { n9 = n; break; }
  const v9 = n9 * 0.25 * 0.75;
  chk(9, '7.5', 'np = 75 가 되는 n 을 훑어 찾으면 ' + n9 + ' · 분산 npq = ' + v9 + ' (보기 56.25) · σ = √' + v9 + ' = ' + Math.sqrt(v9) + ' · n 자체는 ' + n9 + ' (보기 300)');

  // 10 — 꼬리 확률에서 z 를 되찾아 m 을 구한다
  const z10 = zFromTail(0.0228);
  chk(10, '53', '꼬리 확률 0.0228 에서 z 를 되찾으면 ' + z10 + ' (≈2) · m = 63 − 2×5 = ' + (63 - 2 * 5) + ' · 되넣으면 P(X≥63) = ' + tail((63 - 53) / 5) + ' ✓ · 왼쪽으로 보면 ' + (63 + 10) + ' (보기 73) · σ 를 한 번만 빼면 ' + (63 - 5) + ' (보기 58) · σ 를 아예 곱하지 않으면 ' + (63 - 2) + ' (보기 61)');

  // 11 — σ 를 실제로 키워 가운데 확률과 높이를 잰다
  const c1 = P(-1, 1), c2 = R4(I(-0.5, 0.5));
  chk(11, '가운데가 낮아지고 옆으로 퍼진다', 'N(0,1²) 에서 평균 ±1 안의 확률 ' + c1 + ' · σ 를 2 로 키우면 같은 구간은 z 로 ±0.5 라 ' + c2 + ' 로 줄어든다(가운데에 덜 몰린다) · 두 분포 모두 전체 넓이는 ' + R4(I(-12, 12)) + ' 로 1 (보기 "넓이가 커진다"는 틀림) · 봉우리 높이는 ' + R4(phi(0)) + ' → ' + R4(phi(0) / 2) + ' 로 낮아진다');

  // 12 — 상위 6.68 % 의 경계를 이분법으로 직접 찾는다
  let a12 = 300, lo = 300, hi = 400;
  for (let i = 0; i < 80; i++) { const md = (lo + hi) / 2; if (tail((md - 300) / 20) > 0.0668) lo = md; else hi = md; }
  a12 = Math.round((lo + hi) / 2 * 100) / 100;
  chk(12, '330 g', '오른쪽 꼬리가 0.0668 이 되는 경계를 이분법으로 찾으면 ' + a12 + ' g · 그때 z = ' + R4((a12 - 300) / 20) + ' 이고 꼬리 확률 ' + tail((a12 - 300) / 20) + ' ✓ · z=2 로 읽으면 ' + (300 + 40) + ' (보기 340) · 왼쪽으로 보면 ' + (300 - 30) + ' (보기 270) · 확률을 그대로 더하면 ' + (300 + 6.68) + ' (보기 306.68)');
};
