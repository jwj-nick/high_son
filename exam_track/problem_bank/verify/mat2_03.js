module.exports = function ({ S, chk, dist }) {
  chk(1, '(−1, 3)', '(' + (3 - 4) + ',' + (-2 + 5) + ')');
  { const L = (x, y) => 2 * x - 3 * y - 6; chk(2, '2x − 3y − 6 = 0', '(1,1)→(3,0):' + L(3, 0) + ' (−2,−1)→(0,−2):' + L(0, -2)); }
  chk(3, '(x + 1)² + (y + 2)² = 9', '중심 (−1,2)→(−1,−2)');
  { const L = (x, y) => x - 2 * y - 3; chk(4, 'x − 2y − 3 = 0', '(0,3)→(3,0):' + L(3, 0) + ' (−1,1)→(1,−1):' + L(1, -1)); }
  { const B = [3, 4]; const M = [(1 + B[0]) / 2, (2 + B[1]) / 2]; chk(5, '(3, 4)', '중점=' + M + ' 직선대입=' + (M[0] + M[1] - 5) + ' AB기울기=' + (B[1] - 2) / (B[0] - 1) + ' 거리 ' + Math.abs(1 + 2 - 5) / Math.SQRT2 + ',' + Math.abs(3 + 4 - 5) / Math.SQRT2); }
  { const f = (x, y) => x * x + y * y - 1; const p = [-2, -2]; chk(6, 'f(−x − 1, y + 2) = 0', '(1,0)→(2,−2)→(−2,−2) 최종식 대입=' + f(-p[0] - 1, p[1] + 2)); }
  chk(7, '−3, −3', '꼭짓점 (2,1)→(−1,−2)');
  { let best = Infinity; for (let x = -20; x <= 30; x += 0.001) { const v = dist([2, 3], [x, 0]) + dist([x, 0], [6, 1]); if (v < best) best = v; } chk(8, '4√2', 'min≈' + best.toFixed(5) + ' 4√2=' + (4 * Math.SQRT2).toFixed(5)); }
  chk(9, '(−1, 3)', '중심 (1,−3)');
  { const a = -4, b = -8; chk(10, '−12', '이동 후 원점값=' + (a * (0 - 2) + b) + ' 대칭 후 (1)=' + (a * (-1 - 2) + b)); }
  { const p = [5, 3]; const q = [p[1], p[0]]; const r = [q[0], -q[1]]; chk(11, '(5, 3)', '(5,3)→' + q + '→' + r); }
  chk(12, 'y축', '(x,y)→(−x,y)');
};
