/* alg_08 검산 — 수열의 합. 공식을 쓰지 않고 for 문으로 항을 하나씩 더한다.
 *   · 모든 Σ 는 실제 루프로 계산한다(공식 유도의 오류가 그대로 옮겨 가지 않게).
 *   · 합이 식으로 주어진 문항은 그 식에서 항을 만들어 낸 뒤 다시 더해 되돌아오는지 본다.
 *   · 방정식은 n 을 1부터 넣어 조건을 만족하는 자연수를 찾는다.
 */
module.exports = function ({ chk }) {
  const R6 = (v) => Math.round(v * 1e6) / 1e6, M = (v) => String(v).replace('-', '−');
  const gcd = (a, b) => (b ? gcd(b, a % b) : a);
  const frac = (v) => {
    for (let d = 1; d <= 2000; d++) { const n = v * d; if (Math.abs(n - Math.round(n)) < 1e-9 * d) { const g = gcd(Math.abs(Math.round(n)), d) || 1; const num = Math.round(n) / g, den = d / g; return den === 1 ? M(num) : M(num) + '/' + den; } }
    return String(R6(v));
  };
  /* 시작 lo 부터 끝 hi 까지 f(k) 를 실제로 더한다 */
  const S = (lo, hi, f) => { let s = 0; for (let k = lo; k <= hi; k++) s += f(k); return s; };

  chk(1, String(S(1, 8, (k) => 3 * k + 2)), '항 ' + [1, 2, 3, 8].map((k) => 3 * k + 2).join(',…,') + ' · 루프 합 ' + S(1, 8, (k) => 3 * k + 2) + ' (상수를 한 번만 더하면 ' + (S(1, 8, (k) => 3 * k) + 2) + ')');
  chk(2, String(S(1, 6, (k) => k * k)), '1..6 제곱 합 ' + S(1, 6, (k) => k * k) + ' · 세제곱 합은 ' + S(1, 6, (k) => k * k * k) + ' · 그냥 합은 ' + S(1, 6, (k) => k));

  /* 3·10. 합의 식에서 항을 만들어 낸 뒤 되돌아오는지 확인 */
  const Sa3 = (n) => n * n + 3 * n, a3 = (n) => Sa3(n) - Sa3(n - 1);
  chk(3, String(a3(6)), 'S₅=' + Sa3(5) + ' S₆=' + Sa3(6) + ' → a₆=' + a3(6) + ' · 만든 항을 6개 더하면 ' + S(1, 6, a3) + ' = S₆');
  const Sa10 = (n) => Math.pow(2, n + 1) - 2, a10 = (n) => Sa10(n) - Sa10(n - 1);
  chk(10, String(a10(5)), 'S₄=' + Sa10(4) + ' S₅=' + Sa10(5) + ' → a₅=' + a10(5) + ' · 만든 항 ' + [1, 2, 3, 4, 5].map(a10).join(',') + ' 의 합 ' + S(1, 5, a10));

  chk(4, String(S(1, 5, (k) => Math.pow(2 * k - 1, 2))), '항 ' + [1, 2, 3, 4, 5].map((k) => Math.pow(2 * k - 1, 2)).join('+') + ' = ' + S(1, 5, (k) => Math.pow(2 * k - 1, 2)) +
    ' · 합의 제곱이라면 ' + Math.pow(S(1, 5, (k) => 2 * k - 1), 2));

  chk(5, frac(S(1, 12, (k) => 1 / ((2 * k - 1) * (2 * k + 1)))), '루프 합 ' + R6(S(1, 12, (k) => 1 / ((2 * k - 1) * (2 * k + 1)))) +
    ' · ½ 없이 쪼개면 ' + R6(2 * S(1, 12, (k) => 1 / ((2 * k - 1) * (2 * k + 1)))));

  chk(6, String(S(1, 10, (k) => (k + 1) * (k + 1)) - S(1, 10, (k) => k * k)), '앞 합 ' + S(1, 10, (k) => (k + 1) * (k + 1)) + ' 뒤 합 ' + S(1, 10, (k) => k * k) +
    ' → 차 ' + (S(1, 10, (k) => (k + 1) * (k + 1)) - S(1, 10, (k) => k * k)) + ' · 두 합의 합은 ' + (S(1, 10, (k) => (k + 1) * (k + 1)) + S(1, 10, (k) => k * k)));

  let n7 = null; for (let n = 1; n <= 300; n++) if (S(1, n, (k) => 2 * k) === 210) { n7 = n; break; }
  chk(7, String(n7), 'n=' + n7 + ' 일 때 합 ' + S(1, n7, (k) => 2 * k) + ' · n=20 이면 ' + S(1, 20, (k) => 2 * k));

  chk(8, String(S(4, 10, () => 4)), 'k=4..10 은 ' + (10 - 4 + 1) + '개 · 합 ' + S(4, 10, () => 4) + ' · k=1..10 이면 ' + S(1, 10, () => 4));

  const v9 = S(1, 12, (k) => 1 / (Math.sqrt(2 * k + 1) + Math.sqrt(2 * k - 1)));
  chk(9, frac(Math.round(v9 * 1e9) / 1e9), '루프 합 ' + R6(v9) + ' · 첫 항 ' + R6(1 / (Math.sqrt(3) + 1)) + ' = ½(√3−1)=' + R6((Math.sqrt(3) - 1) / 2) + ' · ½ 없이면 ' + R6(2 * v9));

  chk(11, String(S(1, 6, (k) => k * k * k - k)), '항 ' + [1, 2, 3, 4, 5, 6].map((k) => k * k * k - k).join('+') + ' = ' + S(1, 6, (k) => k * k * k - k) +
    ' · Σk³=' + S(1, 6, (k) => k * k * k) + ' Σk=' + S(1, 6, (k) => k));

  chk(12, String(S(1, 10, (k) => k * (k + 2))), '항 ' + [1, 2, 3, 10].map((k) => k * (k + 2)).join(',…,') + ' · 루프 합 ' + S(1, 10, (k) => k * (k + 2)) +
    ' · Σk×Σ(k+2) 라면 ' + S(1, 10, (k) => k) * S(1, 10, (k) => k + 2));
};
