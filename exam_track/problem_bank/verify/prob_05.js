// prob_05 정답키 재검산 — 공식(E = np, V = npq, V = E(X²) − {E(X)}²)을 쓰지 않고,
// 확률분포를 통째로 만들어 "값 × 확률"과 "편차의 제곱 × 확률"을 직접 더하는 경로로.
module.exports = function ({ chk }) {
  const g = (a, b) => (b ? g(b, a % b) : a);
  const Q = (n, d) => { const q = g(Math.abs(n), d) || 1; return (n / q) + (d / q === 1 ? '' : '/' + d / q); };
  const R = (v) => Math.round(v * 1e9) / 1e9;
  // 분포를 [값, 확률] 목록으로 받아 평균·분산을 정의대로 계산한다
  const EV = (dist) => {
    const p = dist.reduce((a, d) => a + d[1], 0);
    const m = dist.reduce((a, d) => a + d[0] * d[1], 0);
    const v = dist.reduce((a, d) => a + (d[0] - m) * (d[0] - m) * d[1], 0);   // 편차의 제곱의 평균
    const e2 = dist.reduce((a, d) => a + d[0] * d[0] * d[1], 0);
    return { p: R(p), m: R(m), v: R(v), e2: R(e2), s: R(Math.sqrt(v)) };
  };
  // 이항분포의 분포표를 확률을 하나씩 쌓아 만든다(공식을 쓰지 않고 재귀로)
  const binom = (n, p) => { let d = [[0, 1]]; for (let i = 0; i < n; i++) { const nx = new Map(); for (const [k, q] of d) { nx.set(k, (nx.get(k) || 0) + q * (1 - p)); nx.set(k + 1, (nx.get(k + 1) || 0) + q * p); } d = [...nx.entries()].sort((a, b) => a[0] - b[0]); } return d; };

  // 1 — 분포를 만들어 값 × 확률을 더한다
  const d1 = [1, 2, 3, 4].map((k) => [k, k / 10]);
  const r1 = EV(d1);
  chk(1, '3', '확률의 합 ' + r1.p + ' · 값 × 확률의 합 = ' + r1.m + ' · 값들의 단순 평균은 ' + (10 / 4) + ' (보기 5/2) · P(X=3) = ' + (3 / 10) + ' (보기 3/10)');

  // 2 — E(X)=4, V(X)=3 인 분포를 실제로 지어 E(X²) 를 직접 잰다
  const d2 = [[4 - Math.sqrt(3), 0.5], [4 + Math.sqrt(3), 0.5]];
  const r2 = EV(d2);
  chk(2, '19', '평균 ' + r2.m + ' 분산 ' + r2.v + ' 인 분포를 지어 E(X²) 를 직접 재면 ' + r2.e2 + ' · V + E 로 하면 ' + (3 + 4) + ' (보기 7) · E² − V 로 하면 ' + (16 - 3) + ' (보기 13) · V × E² 는 ' + (3 * 16) + ' (보기 48)');

  // 3 — X 를 실제로 만들어 4X−3 의 분포를 새로 만들고 정의대로 잰다
  const d3 = [[3, 0.5], [7, 0.5]];
  const r3 = EV(d3), r3b = EV(d3.map((d) => [4 * d[0] - 3, d[1]]));
  chk(3, 'E = 17, V = 64', 'X 의 평균 ' + r3.m + ' 분산 ' + r3.v + ' · 4X−3 의 분포 ' + d3.map((d) => 4 * d[0] - 3).join(',') + ' 를 정의대로 재면 평균 ' + r3b.m + ' 분산 ' + r3b.v + ' · 분산에서 3 을 빼면 ' + (64 - 3) + ' (보기 61) · 상수를 빼먹으면 평균 ' + (4 * 5) + ' (보기 20) · 계수를 제곱 안 하면 ' + (4 * 4) + ' (보기 16)');

  // 4 — 주사위 여섯 눈을 전부 훑어 받는 금액을 매기고 평균을 낸다
  const pay = [1, 2, 3, 4, 5, 6].map((f) => [f % 3 === 0 ? 100 : -50, 1 / 6]);
  const r4 = EV(pay);
  chk(4, '0 원', '주사위 여섯 눈에 금액을 매겨(3·6 은 +100, 나머지는 −50) 평균을 내면 ' + r4.m + ' 원 · 두 금액의 단순 평균은 ' + ((100 - 50) / 2) + ' (보기 25) · 가장 자주 나오는 값은 ' + (-50) + ' (보기 −50) · 여섯 번 던져 3의 배수가 두 번이면 ' + (2 * 100 - 4 * 50) + ' 원으로 상쇄');

  // 5 — B(50, 1/5) 분포표를 재귀로 쌓아 평균·분산을 직접 잰다
  const b5 = binom(50, 0.2), r5 = EV(b5);
  chk(5, 'E = 10, V = 8', '분포표를 51 칸 만들어 정의대로 재면 평균 ' + r5.m + ' 분산 ' + r5.v + ' · 표준편차 ' + R(r5.s) + ' (보기 2√2 ≈ ' + R(2 * Math.sqrt(2)) + ') · q 를 안 곱하면 ' + (50 * 0.2) + ' (보기 10) · 확률의 합 ' + r5.p);

  // 6 — B(400, 0.1) 도 분포표를 실제로 만든다
  const b6 = binom(400, 0.1), r6 = EV(b6);
  chk(6, '6', '분포표 401 칸을 만들어 재면 평균 ' + r6.m + ' 분산 ' + r6.v + ' 표준편차 ' + R(r6.s) + ' · 평균은 ' + r6.m + ' (보기 40) · 분산은 ' + r6.v + ' (보기 36) · q 를 빼먹은 √40 = ' + R(Math.sqrt(40)) + ' (보기 2√10)');

  // 7 — n 을 1 부터 훑어 조건을 만족하는 (n, p) 를 실제로 찾는다
  let n7 = null, p7 = null;
  for (let n = 1; n <= 300 && n7 === null; n++) { const p = 12 / n; if (p > 0 && p < 1 && Math.abs(n * p * (1 - p) - 9.6) < 1e-9) { n7 = n; p7 = R(p); } }
  chk(7, '60', 'n 을 1 부터 훑어 np = 12 이면서 npq = 9.6 인 것을 찾으면 n = ' + n7 + ' (그때 p = ' + p7 + ') · V/E = ' + R(9.6 / 12) + ' 는 q 이고 이것을 p 로 보면 n = ' + R(12 / 0.8) + ' (보기 15) · p 자체는 ' + p7 + ' (보기 0.2)');

  // 8 — 균등분포를 만들어 편차의 제곱을 직접 평균 낸다
  const d8 = [1, 2, 3, 4, 5].map((k) => [k, 1 / 5]);
  const r8 = EV(d8);
  chk(8, '2', '편차의 제곱의 평균 = ' + r8.v + ' · E(X²) = ' + r8.e2 + ' (보기 11) · 표준편차 ' + R(r8.s) + ' (보기 √2 ≈ ' + R(Math.sqrt(2)) + ') · 평균을 제곱 안 하면 ' + (11 - 3) + ' (보기 8)');

  // 9 — V(X)=5 인 분포를 지어 −4X+7 의 분산을 새로 잰다
  const d9 = [[-Math.sqrt(5), 0.5], [Math.sqrt(5), 0.5]];
  const r9 = EV(d9), r9b = EV(d9.map((d) => [-4 * d[0] + 7, d[1]]));
  chk(9, '80', 'V(X) = ' + r9.v + ' 인 분포를 지어 −4X+7 로 옮긴 뒤 정의대로 재면 분산 ' + r9b.v + ' · 계수를 그대로 곱하면 ' + (-4 * 5) + ' (보기 −80) · 상수를 더하면 ' + (80 + 7) + ' (보기 87) · 절댓값만 곱하면 ' + (4 * 5) + ' (보기 20) · 표준편차는 ' + R(r9b.s) + ' = 4√5');

  // 10 — B(5, 1/4) 의 분포표를 재귀로 만들어 X=2 칸을 읽는다
  const b10 = binom(5, 0.25);
  const p2 = b10.find((d) => d[0] === 2)[1];
  chk(10, '135/512', '분포표를 만들어 X=2 칸을 읽으면 ' + R(p2) + ' = ' + Q(Math.round(p2 * 1024), 1024) + ' · 1024 을 분모로 한 여섯 칸 ' + b10.map((d) => Math.round(d[1] * 1024)).join(',') + ' 의 합 ' + b10.reduce((a, d) => a + Math.round(d[1] * 1024), 0) + ' · 조합을 안 곱하면 ' + R(27 / 1024) + ' (보기 27/1024) · 실패를 2 로 보면 ' + R(10 * (1 / 16) * (9 / 16)) + ' (보기 45/128) · 지수를 뒤바꾸면 ' + R(10 * (1 / 64) * (9 / 16)) + ' (보기 45/512)');

  // 11 — 확률의 합이 1 이 되는 a 를 훑어 찾은 뒤 평균을 잰다
  let a11 = null;
  for (let a = 0; a <= 1.0001; a += 0.0001) { if (Math.abs(1 / 6 + a + 1 / 3 + 1 / 4 - 1) < 5e-5) { a11 = Math.round(a * 10000) / 10000; break; } }
  const d11 = [[0, 1 / 6], [1, a11], [2, 1 / 3], [3, 1 / 4]];
  const r11 = EV(d11);
  chk(11, '5/3', '확률의 합이 1 이 되는 a 를 훑어 찾으면 ' + a11 + ' (= 1/4) · 그 분포의 평균 ' + r11.m + ' = ' + Q(20, 12) + ' · 확률의 합 ' + r11.p + ' · a 자체는 ' + a11 + ' (보기 1/4) · 18/12 이면 ' + R(18 / 12) + ' (보기 3/2)');

  // 12 — B(4, 1/6) 분포표를 만들어 값의 제곱 × 확률을 직접 더한다
  const b12 = binom(4, 1 / 6), r12 = EV(b12);
  chk(12, '1', '분포표 다섯 칸(1296 을 분모로 ' + b12.map((d) => Math.round(d[1] * 1296)).join(',') + ')을 만들어 값의 제곱 × 확률을 더하면 E(X²) = ' + r12.e2 + ' · 평균 ' + R(r12.m) + ' = 2/3 이라 평균의 제곱은 ' + R(r12.m * r12.m) + ' (보기 4/9) · 분산은 ' + R(r12.v) + ' (보기 5/9) · 둘을 더하면 ' + R(r12.v + r12.m * r12.m));
};
