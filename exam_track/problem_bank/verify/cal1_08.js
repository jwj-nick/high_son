// cal1_08 정답키 재검산 — 문항의 풀이와 다른 경로로.
// 넓이는 공식이나 조각 나누기를 쓰지 않고 |f−g| 를 통째로 잘게 쪼개 더한다(교점을 몰라도 값이 나온다).
module.exports = function ({ chk, near }) {
  const R6 = (v) => Math.round(v * 1e6) / 1e6;
  const F = (v) => { for (let d = 1; d <= 300; d++) { const n = v * d; if (Math.abs(n - Math.round(n)) < 1e-6 * d) { const g = (a, b) => (b ? g(b, a % b) : a); const q = g(Math.abs(Math.round(n)), d) || 1; return (Math.round(n) / q) + (d / q === 1 ? '' : '/' + d / q); } } return String(R6(v)); };
  const I = (f, a, b, N) => { N = N || 60000; const h = (b - a) / N; let s = f(a) + f(b); for (let i = 1; i < N; i++) s += f(a + i * h) * (i % 2 ? 4 : 2); return s * h / 3; };
  // 두 곡선 사이의 넓이를 |f−g| 로 통째 적분 — 위아래를 정하지 않아도 되고, 조각도 저절로 갈린다
  const A = (f, g, a, b) => I((x) => Math.abs(f(x) - g(x)), a, b);
  const Z = () => 0;
  // 교점을 수치로 찾아 문항이 쓴 것과 맞는지도 본다
  const roots = (f, lo, hi) => { const r = []; let p = f(lo); for (let x = lo + 0.0007123; x <= hi; x += 0.0007123) { const c = f(x); if (p * c < 0) { let a = x - 0.0007123, b = x; for (let i = 0; i < 60; i++) { const m = (a + b) / 2; if (f(a) * f(m) <= 0) b = m; else a = m; } r.push(R6((a + b) / 2)); } else if (Math.abs(c) < 1e-12) r.push(R6(x)); p = c; } return r; };

  // 1 — 절댓값을 통째로 적분(조각을 나누지 않는다)
  const f1 = (x) => x * x - 4;
  chk(1, '32/3', '|f| 통째 적분 ' + F(A(f1, Z, -2, 2)) + ' · 부호 그대로면 ' + F(I(f1, -2, 2)) + ' · 한쪽만 = ' + F(A(f1, Z, 0, 2)) + ' · 교점 ' + roots(f1, -4, 4));

  // 2 — 위아래를 정하지 않고 |x²−2x| 로
  chk(2, '4/3', '|x²−2x| 적분 ' + F(A((x) => x * x, (x) => 2 * x, 0, 2)) + ' · 부호 그대로 (x²−2x) = ' + F(I((x) => x * x - 2 * x, 0, 2)) + ' · 6 대신 3 으로 나누면 ' + F(2 ** 3 / 3));

  // 3 — 교점을 수치로 찾고 |f| 통째 적분
  const f3 = (x) => x ** 3 - 9 * x;
  chk(3, '81/2', '교점 ' + roots(f3, -5, 5) + ' · |f| 통째 ' + F(A(f3, Z, -3, 3)) + ' · 부호 그대로 ' + F(I(f3, -3, 3)) + ' · 한쪽만 ' + F(A(f3, Z, 0, 3)) + ' · 이차 공식을 억지로 쓰면 ' + F(6 ** 3 / 6));

  // 4 — 어느 쪽이 위인지 대입으로 확인하고 |f−g| 로
  const a4 = A((x) => x ** 3, (x) => x * x, 0, 1);
  chk(4, '1/12', '|x³−x²| 적분 ' + F(a4) + ' · x=0.5 에서 x²=' + 0.25 + ' x³=' + 0.125 + ' → x² 이 위 · 각각의 정적분을 더하면 ' + F(I((x) => x * x, 0, 1) + I((x) => x ** 3, 0, 1)) + ' (보기 7/12)');

  // 5 — 교점을 모른 채 |f| 를 0~4 통째로
  const f5 = (x) => x * x - 3 * x;
  chk(5, '19/3', '|f| 통째 ' + F(A(f5, Z, 0, 4)) + ' · 부호 그대로 ' + F(I(f5, 0, 4)) + ' · 교점 ' + roots(f5, -1, 5) + ' · [0,3] 조각 ' + F(A(f5, Z, 0, 3)) + ' · [3,4] 조각 ' + F(A(f5, Z, 3, 4)));

  // 6 — 위치 변화량과 이동 거리를 나란히
  const v6 = (t) => 3 * t * t - 12 * t;
  chk(6, '−25', '위치 변화 ∫v = ' + F(I(v6, 0, 5)) + ' · 이동 거리 ∫|v| = ' + F(I((t) => Math.abs(v6(t)), 0, 5)) + ' (보기 39) · v=0 인 t = ' + roots(v6, -1, 6) + ' · 12t 를 60 으로 잘못 보면 ' + (125 - 60));

  // 7 — 절댓값 적분 한 줄로(조각을 세지 않는다)
  const v7 = (t) => t * t - 5 * t + 6;
  chk(7, '55/3', '이동 거리 ∫|v| = ' + F(I((t) => Math.abs(v7(t)), 0, 6)) + ' · 위치 변화 ∫v = ' + F(I(v7, 0, 6)) + ' (보기 18) · v=0 인 t = ' + roots(v7, -1, 7) + ' · [2,3] 조각을 빼면 ' + F(I((t) => Math.abs(v7(t)), 0, 6) - I((t) => Math.abs(v7(t)), 2, 3)) + ' (보기 109/6)');

  // 8 — 공식을 쓰지 않고 적분으로
  const a8 = A((x) => x * x, (x) => x + 6, -2, 3);
  chk(8, '125/6', '|x²−(x+6)| 적분 ' + F(a8) + ' · 교점 ' + roots((x) => x * x - x - 6, -5, 5) + ' · 6 대신 3 으로 나누면 ' + F(125 / 3) + ' · (β³−α³)/6 로 보면 ' + F((27 + 8) / 6));

  // 9 — a 를 이분법으로 직접 찾는다(식을 세우지 않는다)
  const tot9 = I((x) => x * x, 1, 3), half = tot9 / 2;
  let lo = 1, hi = 3; for (let i = 0; i < 80; i++) { const m = (lo + hi) / 2; if (I((x) => x * x, 1, m) < half) lo = m; else hi = m; }
  const a9 = (lo + hi) / 2;
  chk(9, '14', '전체 ' + F(tot9) + ' 절반 ' + F(half) + ' · 이등분하는 a = ' + R6(a9) + ' → a³ = ' + R6(a9 ** 3) + ' · 구간을 반으로 나눈 a=2 라면 왼쪽 넓이 ' + F(I((x) => x * x, 1, 2)) + ' 로 절반이 아니다(a³=8)');

  // 10 — |x³−x| 를 −1~1 통째로
  const a10 = A((x) => x ** 3, (x) => x, -1, 1);
  chk(10, '1/2', '|x³−x| 적분 ' + F(a10) + ' · 부호 그대로 ' + F(I((x) => x - x ** 3, -1, 1)) + ' (보기 0) · 한쪽만 ' + F(A((x) => x ** 3, (x) => x, 0, 1)) + ' · x=−0.5 에서 x³=' + (-0.125) + ' &gt; x=' + (-0.5) + ' 로 위아래가 뒤집힌다 · 이차 공식을 억지로 쓰면 ' + F(2 ** 3 / 6));

  // 11 — 최고점을 이분법으로 찾고 거기까지 적분
  const v11 = (t) => 30 - 10 * t;
  const t11 = roots(v11, 0, 10)[0];
  chk(11, '45 m', 'v=0 인 t = ' + t11 + ' · 그때까지 ∫v = ' + F(I(v11, 0, t11)) + ' · 끝까지(t=6) ∫v = ' + F(I(v11, 0, 6)) + ' (보기 0) · −10t 를 빼먹으면 ' + 30 * 3);

  // 12 — a 를 훑어 넓이가 9 가 되는 값을 찾는다
  let a12 = null;
  for (let a = 0.1; a <= 8; a += 0.0001) { const s = A((x) => x * x, (x) => -x * x + 2 * a * x, 0, a); if (Math.abs(s - 9) < 2e-4) { a12 = Math.round(a * 1e4) / 1e4; break; } }
  chk(12, '3', '넓이가 9 가 되는 a = ' + a12 + ' (그때 넓이 ' + F(A((x) => x * x, (x) => -x * x + 2 * a12 * x, 0, a12)) + ') · a=9 라면 넓이 ' + F(A((x) => x * x, (x) => -x * x + 18 * x, 0, 9)) + ' · a³ = ' + R6(a12 ** 3) + ' 이라 27 은 a 가 아니라 a³ 이다');
};
