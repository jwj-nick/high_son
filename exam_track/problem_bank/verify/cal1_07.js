// cal1_07 정답키 재검산 — 문항의 풀이와 다른 경로로.
// 부정적분·정적분은 전부 "잘게 쪼개 더하기"(심프슨 적분)로 되짚고, 미분이 필요한 곳은 중앙차분을 쓴다.
module.exports = function ({ chk, near }) {
  const R6 = (v) => Math.round(v * 1e6) / 1e6;
  const F = (v) => { // 분수 표기 (분모 200 까지)
    for (let d = 1; d <= 200; d++) { const n = v * d; if (Math.abs(n - Math.round(n)) < 1e-7 * d) { const g = (a, b) => (b ? g(b, a % b) : a); const q = g(Math.abs(Math.round(n)), d) || 1; return (Math.round(n) / q) + (d / q === 1 ? '' : '/' + d / q); } }
    return String(R6(v));
  };
  // 심프슨 — 다항식이면 오차 없이 정확하다(4차까지)
  const I = (f, a, b, N) => { N = N || 2000; const h = (b - a) / N; let s = f(a) + f(b); for (let i = 1; i < N; i++) s += f(a + i * h) * (i % 2 ? 4 : 2); return s * h / 3; };
  const D = (f, x, h) => (f(x + (h || 1e-4)) - f(x - (h || 1e-4))) / (2 * (h || 1e-4));

  // 1 — 부정적분은 "미분해서 되돌아오는가"로 판정한다. 후보 넷을 전부 미분해 4x³−6x+5 와 맞춰 본다
  const f1 = (x) => 4 * x ** 3 - 6 * x + 5;
  const cands1 = { 'x⁴−3x²+5x+C': (x) => x ** 4 - 3 * x * x + 5 * x, '4x⁴−6x²+5x+C': (x) => 4 * x ** 4 - 6 * x * x + 5 * x, '12x²−6+C': (x) => 12 * x * x - 6 };
  const hit1 = Object.keys(cands1).filter((k) => [-2, -0.5, 1.3, 2.7].every((x) => near(D(cands1[k], x), f1(x), 1e-4)));
  chk(1, 'x⁴ − 3x² + 5x + C', '미분해서 4x³−6x+5 가 되는 후보 = ' + hit1.join(',') + ' · +C 는 미분에서 사라지므로 부정적분에는 반드시 붙는다');

  // 2 — 정적분은 잘게 쪼개 더한다. 부호까지 그대로 나오는지 아래/위 넓이를 따로도 센다
  const v2 = I((x) => 2 * x - 4, 0, 3);
  const below = I((x) => Math.max(0, -(2 * x - 4)), 0, 3, 20000), above = I((x) => Math.max(0, 2 * x - 4), 0, 3, 20000);
  chk(2, '−3', '리만합 ' + R6(v2) + ' · 아래쪽 넓이 ' + R6(below) + ' 위쪽 ' + R6(above) + ' → ' + R6(above - below) + ' (부호 있는 넓이) · 순서를 바꾸면 ' + R6(I((x) => 2 * x - 4, 3, 0)));

  // 3 — C 를 구하지 않고, F(1) = F(2) − ∫(1→2)F' 로 되짚는다
  const v3 = 5 - I((x) => 3 * x * x + 4 * x, 1, 2);
  chk(3, '−8', 'F(1) = F(2) − ∫(1→2)F′ = 5 − ' + R6(I((x) => 3 * x * x + 4 * x, 1, 2)) + ' = ' + R6(v3) + ' · C 를 쓰지 않은 경로 · F′(1)=' + (3 + 4) + ' (보기 7 의 정체)');

  // 4 — 대칭 성질을 쓰지 않고 통째로 적분한다
  const g4 = (x) => 2 * x ** 3 - 5 * x * x + 4 * x - 1;
  const v4 = I(g4, -3, 3);
  chk(4, '−96', '통째 적분 ' + R6(v4) + ' · 짝수 차수만 한 번 = ' + R6(I((x) => -5 * x * x - 1, 0, 3)) + ' (두 배 안 한 값) · 상수항을 빼면 ' + R6(2 * I((x) => -5 * x * x, 0, 3)) + ' · 홀수 차수만 = ' + R6(I((x) => 2 * x ** 3 + 4 * x, -3, 3)));

  // 5 — 실제 함수 하나를 지어 두 조건을 맞춘 뒤 ∫(5→0) 을 직접 잰다
  //     f 를 이차식 ax²+bx+c 로 두고 ∫(0→2)f=5, ∫(2→5)f=3 을 만족하게 잡는다(a 는 아무 값)
  const a5 = 1; // ∫(0→2)(x²+bx+c)=8/3+2b+2c=5 · ∫(2→5)(x²+bx+c)=39+10.5b+3c=3
  const b5 = (5 - 8 / 3 - 3 * (3 - 39) / 3 * 0), _ = 0;
  // 두 식을 풀면: 2b+2c = 7/3 · 10.5b+3c = −36
  const det = 2 * 3 - 2 * 10.5, bb = ((7 / 3) * 3 - 2 * (-36)) / det, cc = (2 * (-36) - (7 / 3) * 10.5) / det;
  const f5 = (x) => a5 * x * x + bb * x + cc;
  chk(5, '−8', '조건을 만족하는 f 를 지어 확인: ∫(0→2)f=' + R6(I(f5, 0, 2)) + ' ∫(2→5)f=' + R6(I(f5, 2, 5)) + ' → ∫(5→0)f=' + R6(I(f5, 5, 0)) + ' · ∫(0→5)f=' + R6(I(f5, 0, 5)) + ' (보기 8 의 정체)');

  // 6 — 정적분 함수를 실제로 만들어 수치미분한다
  const G6 = (x) => I((t) => t ** 3 - 2 * t, 1, x, 4000);
  const pts6 = [-1.4, 0.6, 2.3, 3.1];
  const okd = pts6.every((x) => near(D(G6, x, 1e-3), x ** 3 - 2 * x, 1e-4));
  chk(6, 'x³ − 2x', '정적분 함수를 수치미분: ' + pts6.map((x) => 'x=' + x + '→' + R6(D(G6, x, 1e-3)) + '(식 ' + R6(x ** 3 - 2 * x) + ')').join(' ') + ' 일치=' + okd + ' · 아래끝을 0 으로 바꿔도 미분값은 같다: x=2.3→' + R6(D((x) => I((t) => t ** 3 - 2 * t, 0, x, 4000), 2.3, 1e-3)));

  // 7 — k 를 미지수로 풀지 않고, k 를 훑어 자기일관인 값을 찾는다(고정점)
  let k7 = null;
  for (let k = -5; k <= 5; k += 0.0001) { const lhs = I((t) => 2 * t + 3 * k, 0, 1); if (Math.abs(lhs - k) < 5e-5) { k7 = Math.round(k * 1e4) / 1e4; break; } }
  const f7 = (x) => 2 * x + 3 * k7;
  chk(7, '1/2', '자기일관인 k = ' + k7 + ' (∫(0→1)f = ' + R6(I(f7, 0, 1)) + ' 로 k 와 같다) → f(1) = ' + F(f7(1)) + ' · k 를 +1/2 로 잘못 두면 f(1)=' + F(2 + 1.5));

  // 8 — 대칭 구간이 아님을 값으로 보인다
  const g8 = (x) => 3 * x * x + 2 * x;
  chk(8, '12', '리만합 ' + R6(I(g8, -1, 2)) + ' · 대칭 성질을 억지로 쓰면 2×∫(0→2)3x²=' + R6(2 * I((x) => 3 * x * x, 0, 2)) + ' (보기 24) · ∫(−1→1)=' + R6(I(g8, -1, 1)) + ' 로 이쪽이었다면 0 이 아니라 2 다');

  // 9 — C 를 구하지 않고 f(2) = f(1) + ∫(1→2)f′ 로
  const v9 = 3 + I((x) => 6 * x * x - 4 * x, 1, 2);
  chk(9, '11', 'f(2) = f(1) + ∫(1→2)f′ = 3 + ' + R6(I((x) => 6 * x * x - 4 * x, 1, 2)) + ' = ' + R6(v9) + ' · f′(2)=' + (24 - 8) + ' (보기 16 의 정체) · C 없이 계산하면 ' + (16 - 8) + ' (보기 8)');

  // 10 — 답이 "없다"임을 보인다: k 후보 전 구간에서 자기일관인 값이 하나도 없다
  let found10 = null, worst = 1e9;
  for (let k = -50; k <= 50; k += 0.001) { const lhs = I((t) => 3 * t * t + k, 0, 1); const gap = Math.abs(lhs - k); if (gap < worst) worst = gap; if (gap < 1e-6) found10 = k; }
  chk(10, '그런 함수 f 는 존재하지 않는다', 'k 를 −50~50 에서 0.001 간격으로 훑어 ∫(0→1)(3t²+k)dt = k 인 k = ' + found10 + ' · 가장 가까워도 차가 ' + R6(worst) + ' 로 늘 1 이다(k−k=1 이라는 모순) · k=−1 이면 좌변 ' + R6(I((t) => 3 * t * t - 1, 0, 1)) + ' ≠ −1');

  // 11 — 주어진 식을 미분하지 않고, 정적분이 그 식이 되는 f 를 수치미분으로 되찾는다
  const G11 = (x) => x ** 3 - 2 * x * x + x;
  const v11 = D(G11, 2, 1e-4);
  chk(11, '5', '∫(0→x)f = x³−2x²+x 를 x=2 에서 수치미분 → f(2) = ' + R6(v11) + ' · 되짚기: ∫(0→2)f = ' + R6(I((x) => D(G11, x, 1e-4), 0, 2)) + ' 이고 G11(2) = ' + G11(2) + ' (보기 2 의 정체)');

  // 12 — 값과 "도형의 넓이"를 따로 잰다
  const g12 = (x) => x * x - 2 * x;
  chk(12, '−4/3 이고, 이 구간에서 x축 아래 부분이 더 크다는 뜻이다', '정적분 ' + F(I(g12, 0, 2)) + ' · 도형의 넓이(부호를 바꿔 더함) ' + F(I((x) => Math.abs(g12(x)), 0, 2, 20000)) + ' · [0,2] 에서 f 의 부호: f(0.5)=' + R6(g12(0.5)) + ' f(1.5)=' + R6(g12(1.5)) + ' 로 줄곧 음수 · f′(1.5)=' + R6(D(g12, 1.5)) + ' 로 증가하는 구간도 있어 "감소한다"는 틀렸다');
};
