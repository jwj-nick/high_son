// prob_07 정답키 재검산 — 공식을 옮겨 적는 대신, 표본을 실제로 뽑는 **몬테카를로 실험**과
// 조건을 만족하는 값을 훑어 찾는 탐색으로 확인한다. 신뢰도의 뜻(005·012)은 구간을 만 번 만들어 세어 본다.
module.exports = function ({ chk }) {
  const R = (v, d) => { const k = Math.pow(10, d === undefined ? 4 : d); return Math.round(v * k) / k; };
  // 재현 가능한 난수(선형합동법)와 정규난수(Box–Muller)
  let seed = 20260908;
  const rnd = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
  const gauss = (m, s) => { const u = Math.max(rnd(), 1e-12), v = rnd(); return m + s * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
  const sampleMean = (m, s, n) => { let a = 0; for (let i = 0; i < n; i++) a += gauss(m, s); return a / n; };
  // 표준정규분포의 넓이(수치적분)
  const phi = (z) => Math.exp(-z * z / 2) / Math.sqrt(2 * Math.PI);
  const I = (a, b) => { const N = 2000, h = (b - a) / N; let s = phi(a) + phi(b); for (let i = 1; i < N; i++) s += phi(a + i * h) * (i % 2 ? 4 : 2); return s * h / 3; };

  // 1 — 크기 16 인 표본을 2 만 번 뽑아 표본평균의 평균과 표준편차를 실제로 잰다
  const ms1 = []; for (let i = 0; i < 20000; i++) ms1.push(sampleMean(60, 12, 16));
  const m1 = ms1.reduce((a, b) => a + b, 0) / ms1.length;
  const s1 = Math.sqrt(ms1.reduce((a, b) => a + (b - m1) * (b - m1), 0) / ms1.length);
  chk(1, '평균 60, 표준편차 3', '크기 16 인 표본을 2 만 번 뽑아 재면 표본평균의 평균 ' + R(m1, 2) + ' 표준편차 ' + R(s1, 2) + ' (이론값 60 과 3) · 모표준편차는 12 (보기 12) · n 으로 나누면 ' + (12 / 16) + ' (보기 0.75) · 평균까지 나누면 ' + (60 / 4) + ' (보기 15)');

  // 2 — n 과 9n 에서 표본평균의 표준편차를 실제로 재어 비를 본다
  const sd = (n) => { const a = []; for (let i = 0; i < 8000; i++) a.push(sampleMean(0, 12, n)); const m = a.reduce((x, y) => x + y, 0) / a.length; return Math.sqrt(a.reduce((x, y) => x + (y - m) * (y - m), 0) / a.length); };
  const sA = sd(4), sB = sd(36);
  chk(2, '1/3 이 된다', 'n=4 일 때 표본평균의 표준편차 ' + R(sA, 3) + ' · n=36(9 배) 일 때 ' + R(sB, 3) + ' · 비 = ' + R(sB / sA, 3) + ' 로 약 1/3 (1/9 = ' + R(1 / 9, 3) + ' 도 3 배 = 3 도 아니다)');

  // 3 — 크기 25 인 표본평균이 84 를 넘는 비율을 실제로 세어 본다
  let over = 0; const N3 = 40000;
  for (let i = 0; i < N3; i++) if (sampleMean(80, 10, 25) >= 84) over++;
  chk(3, '0.0228', '크기 25 인 표본을 4 만 번 뽑아 표본평균이 84 이상인 비율 = ' + R(over / N3) + ' · 이론값 0.5 − ∫(0→2) = ' + R(0.5 - I(0, 2)) + ' · σ 를 10 으로 잘못 나누면 z = 0.4 라 ' + R(0.5 - I(0, 0.4)) + ' (보기 0.3446 근처) · 표 값 그대로면 ' + R(I(0, 2)) + ' (보기 0.4772) · 왼쪽 전부 ' + R(0.5 + I(0, 2)) + ' (보기 0.9772)');

  // 4 — 구간의 양 끝을 직접 만든다
  const se4 = 15 / Math.sqrt(100), h4 = 1.96 * se4;
  chk(4, '59.06 ≤ m ≤ 64.94', 'σ/√n = ' + se4 + ' · 한쪽 폭 1.96 × ' + se4 + ' = ' + R(h4, 4) + ' → ' + R(62 - h4, 2) + ' ~ ' + R(62 + h4, 2) + ' · 길이 ' + R(2 * h4, 2) + ' · σ 를 그대로 쓰면 ±' + R(1.96 * 15, 2) + ' (보기 32.6~91.4) · 절반만 쓰면 ' + R(62 - h4 / 2, 2) + ' ~ ' + R(62 + h4 / 2, 2) + ' (보기 60.53~63.47)');

  // 5 — 신뢰도의 뜻을 실험으로 확인한다: 구간을 만 번 만들어 모평균을 품는 비율을 센다
  const M = 50, S = 10, n5 = 25, se5 = S / Math.sqrt(n5);
  let hit = 0; const T5 = 10000;
  for (let i = 0; i < T5; i++) { const xb = sampleMean(M, S, n5); if (Math.abs(xb - M) <= 1.96 * se5) hit++; }
  chk(5, '같은 방법으로 구간을 100 번 만들면 그중 약 95 개가 모평균을 품는다', '모평균 50 을 알고 있는 상태에서 크기 25 인 표본으로 95 % 구간을 1 만 번 만들어 세면 모평균을 품은 것이 ' + hit + ' 개 = ' + R(hit / T5 * 100, 1) + ' % · 이론값 95 % · 움직이는 것은 구간이고 모평균은 50 으로 고정되어 있다');

  // 6 — 두 신뢰도의 구간 길이를 실제로 계산해 비교한다
  const se6 = 2, L95 = 2 * 1.96 * se6, L99 = 2 * 2.58 * se6;
  chk(6, '더 길다', 'σ/√n = ' + se6 + ' 일 때 95 % 구간의 길이 ' + L95 + ' · 99 % 구간의 길이 ' + L99 + ' → 99 % 쪽이 ' + R(L99 - L95, 2) + ' 만큼 더 길다 · 비 ' + R(L99 / L95, 3) + ' = 2.58/1.96');

  // 7 — n 을 1 부터 올려 가며 조건을 처음 만족하는 값을 찾는다
  let n7 = null;
  for (let n = 1; n <= 5000; n++) { if (2 * 1.96 * 20 / Math.sqrt(n) <= 7) { n7 = n; break; } }
  chk(7, '126', 'n 을 1 부터 올려 길이 2×1.96×20/√n ≤ 7 을 처음 만족하는 값 = ' + n7 + ' · 그때 길이 ' + R(2 * 1.96 * 20 / Math.sqrt(n7), 3) + ' · n=125 면 길이 ' + R(2 * 1.96 * 20 / Math.sqrt(125), 3) + ' 로 7 을 넘는다 (보기 125) · 한쪽 폭으로 풀면 ' + (() => { for (let n = 1; n <= 5000; n++) if (1.96 * 20 / Math.sqrt(n) <= 7) return n; })() + ' (보기 32)');

  // 8 — 나눗셈을 직접
  chk(8, '0.3', '240 ÷ 800 = ' + (240 / 800) + ' · 되돌리면 800 × 0.3 = ' + (800 * 0.3) + ' · 반대는 ' + ((800 - 240) / 800) + ' (보기 0.7) · 자릿수를 밀면 ' + (240 / 8000) + ' (보기 0.03)');

  // 9 — 표준오차를 직접 계산하고, 표본비율을 실제로 뽑아 흩어짐을 확인한다
  const se9 = Math.sqrt(0.4 * 0.6 / 1600), h9 = 1.96 * se9;
  let props = []; for (let t = 0; t < 3000; t++) { let c = 0; for (let i = 0; i < 1600; i++) if (rnd() < 0.4) c++; props.push(c / 1600); }
  const pm = props.reduce((a, b) => a + b, 0) / props.length;
  const ps = Math.sqrt(props.reduce((a, b) => a + (b - pm) * (b - pm), 0) / props.length);
  chk(9, '0.376 ≤ p ≤ 0.424', '표준오차 √(0.4×0.6/1600) = ' + R(se9) + ' · 1600 명을 3000 번 뽑아 재면 표본비율의 표준편차 ' + R(ps) + ' 로 일치 · 한쪽 폭 ' + R(h9) + ' → ' + R(0.4 - h9, 3) + ' ~ ' + R(0.4 + h9, 3) + ' · 1.96 을 안 곱하면 ' + R(0.4 - se9, 4) + ' ~ ' + R(0.4 + se9, 4) + ' (보기 0.3878~0.4122) · p̂q̂ 를 그대로 쓰면 ±' + (0.4 * 0.6) + ' 라 ' + R(0.4 - 0.24, 2) + ' ~ ' + R(0.4 + 0.24, 2) + ' (보기 0.16~0.64)');

  // 10 — n 을 훑어 오차 폭이 정확히 절반이 되는 배수를 찾는다
  const w = (n) => 1.96 * Math.sqrt(0.25 / n);
  let k10 = null;
  for (let k = 2; k <= 40; k++) if (Math.abs(w(1000 * k) - w(1000) / 2) < 1e-9) { k10 = k; break; }
  chk(10, '4 배로 늘린다', 'n=1000 의 오차 폭 ' + R(w(1000)) + ' · 정확히 절반이 되는 배수를 훑어 찾으면 ' + k10 + ' 배 (n=' + (1000 * k10) + ' 에서 ' + R(w(1000 * k10)) + ') · 2 배면 ' + R(w(2000)) + ' 로 절반이 아니다 (보기 2배) · 16 배면 ' + R(w(16000)) + ' 로 1/4 이다 (보기 16배)');

  // 11 — σ 를 훑어 주어진 구간의 길이를 만들어 내는 값을 찾는다
  const L11 = 53.49 - 46.51;
  let s11 = null;
  for (let s = 1; s <= 40; s += 0.0001) { if (Math.abs(2 * 1.96 * s / Math.sqrt(64) - L11) < 5e-5) { s11 = Math.round(s * 100) / 100; break; } }
  chk(11, '14.24', '구간의 길이 ' + R(L11, 2) + ' 를 만드는 σ 를 훑어 찾으면 ' + s11 + ' · 그때 σ/√64 = ' + R(s11 / 8) + ' 이고 한쪽 폭 ' + R(1.96 * s11 / 8) + ' · 길이를 한쪽 폭으로 보면 σ = ' + R(L11 * 8 / 1.96, 2) + ' (보기 28.49) · σ/√n 자체는 ' + R(s11 / 8, 2) + ' (보기 1.78) · 구간의 가운데는 ' + ((46.51 + 53.49) / 2));

  // 12 — 겹치지 않는 두 구간이 실제로 나오는지, 그리고 둘 다 품는 일이 있는지 실험으로 본다
  let both = 0, neither = 0, exactlyOne = 0, disjointPairs = 0;
  const se12 = 10 / Math.sqrt(25);
  for (let t = 0; t < 20000; t++) {
    const a = sampleMean(50, 10, 25), b = sampleMean(50, 10, 25);
    const aL = a - 1.96 * se12, aR = a + 1.96 * se12, bL = b - 1.96 * se12, bR = b + 1.96 * se12;
    if (aR < bL || bR < aL) { disjointPairs++; const hA = aL <= 50 && 50 <= aR, hB = bL <= 50 && 50 <= bR; if (hA && hB) both++; else if (hA || hB) exactlyOne++; else neither++; }
  }
  chk(12, '두 구간 중 적어도 하나는 모평균을 품지 못했다', '모평균 50 을 알고 있는 상태에서 구간 쌍을 2 만 번 만들어 겹치지 않는 쌍 ' + disjointPairs + ' 개를 골라 보면 — 둘 다 품은 경우 ' + both + ' 개(불가능하므로 0), 하나만 품은 경우 ' + exactlyOne + ' 개, 둘 다 못 품은 경우 ' + neither + ' 개 · 겹치지 않는 쌍이 실제로 나오므로 "계산이 잘못되었다"는 틀리고, 하나만 품는 경우가 있으므로 "둘 다 틀렸다"도 틀리다');
};
